#!/usr/bin/env bash
# Rebuild agent/vendor/cordn-session.mjs: the parts of @cordn/cli the project AI
# member uses (docs/adr-team-ai-member.md), bundled and minified into one file.
# About 1.4 MB, against roughly 87 MB for @cordn/cli and its dependency tree in
# node_modules. Pinned versions; the header records them and the input lock hash.
set -euo pipefail
CLI_VERSION=0.10.0
ESBUILD_VERSION=0.25.12
HERE="$(cd "$(dirname "$0")/.." && pwd)"
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
cd "$TMP"
npm init -y >/dev/null
npm i --no-audit --no-fund -q --save-exact "@cordn/cli@${CLI_VERSION}" "esbuild@${ESBUILD_VERSION}" >/dev/null
# Session API, plus what lib/team-ai-join.mjs needs to open Teams join commits
# (the CLI's own ts-mls copy and seal helpers, so nothing is bundled twice).
cat > entry.mjs <<'ENTRY'
export { openPersistentSession, welcomeIdentifier } from './node_modules/@cordn/cli/dist/lib/index.js';
export { encryptGroupPayload, decryptGroupPayload } from './node_modules/@cordn/cli/dist/lib/utils/mlsMessages.js';
export { mlsMessageDecoder, wireformats, senderTypes, defaultProposalTypes } from './node_modules/@cordn/cli/node_modules/ts-mls/dist/src/index.js';
export { verifyEvent } from 'nostr-tools/pure';
ENTRY
LOCK_SHA="$(sha256sum package-lock.json | cut -c1-16)"
./node_modules/.bin/esbuild entry.mjs --bundle --platform=node --format=esm --minify --target=node22 \
  --legal-comments=none --log-level=error \
  --banner:js="// @cordn/cli ${CLI_VERSION} (esbuild ${ESBUILD_VERSION}, lock ${LOCK_SHA}). Generated by agent/scripts/build-cordn-bundle.sh; do not edit.
import{createRequire as __cr}from'node:module';const require=__cr(import.meta.url);" \
  --outfile="$HERE/vendor/cordn-session.mjs"
ls -l "$HERE/vendor/cordn-session.mjs"
